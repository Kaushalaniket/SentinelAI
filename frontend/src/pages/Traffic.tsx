import { useMemo, useState } from 'react'
import { useSearchParams } from 'react-router-dom'
import { api, qs } from '../lib/api'
import {
  formatBytes,
  formatDuration,
  formatNumber,
  formatTimestamp,
  relativeTime,
} from '../lib/format'
import { useApi } from '../lib/useApi'
import type { TrafficRecord, TrafficSummary } from '../lib/types'
import {
  Badge,
  Chip,
  EmptyState,
  ErrorState,
  NoticeBanner,
  OriginBadge,
  PageHeader,
  PageLoader,
  Panel,
  Pagination,
  SeverityBadge,
  Field,
} from '../components/ui'
import { IconRefresh, IconSearch } from '../components/icons'

const CATEGORIES = [
  ['benign', 'Benign'],
  ['ddos', 'DDoS'],
  ['dos', 'DoS'],
  ['portscan', 'Port Scan'],
  ['webattack', 'Web Attack'],
  ['bruteforce', 'Brute Force'],
  ['bot', 'Bot / C2'],
  ['infiltration', 'Infiltration'],
  ['heartbleed', 'Heartbleed'],
]

export default function Traffic() {
  const [params, setParams] = useSearchParams()
  const origin = params.get('origin') ?? ''
  const category = params.get('category') ?? ''
  const q = params.get('q') ?? ''
  const page = Number(params.get('page') ?? 1)
  const [searchDraft, setSearchDraft] = useState(q)
  const [detail, setDetail] = useState<TrafficRecord | null>(null)
  const [action, setAction] = useState<string | null>(null)
  const [actionError, setActionError] = useState<string | null>(null)

  const query = useMemo(
    () =>
      qs({
        origin: origin || undefined,
        category: category || undefined,
        q: q || undefined,
        page,
        page_size: 25,
      }),
    [origin, category, q, page],
  )

  const list = useApi<{ items: TrafficRecord[]; page: number; pages: number; total: number }>(
    `/api/traffic${query}`,
  )
  const summary = useApi<TrafficSummary>('/api/traffic/summary')

  const update = (patch: Record<string, string | null>) => {
    const next = new URLSearchParams(params)
    for (const [key, value] of Object.entries(patch)) {
      if (value === null || value === '') next.delete(key)
      else next.set(key, value)
    }
    if (!('page' in patch)) next.delete('page')
    setParams(next, { replace: true })
  }

  const runAction = async (name: string, fn: () => Promise<unknown>) => {
    setAction(name)
    setActionError(null)
    try {
      await fn()
      list.refetch()
      summary.refetch()
    } catch (err) {
      setActionError(err instanceof Error ? err.message : String(err))
    } finally {
      setAction(null)
    }
  }

  const openDetail = async (id: number) => {
    try {
      setDetail(await api.get<TrafficRecord>(`/api/traffic/${id}`))
    } catch (err) {
      setActionError(err instanceof Error ? err.message : String(err))
    }
  }

  const items = list.data?.items ?? []

  return (
    <div className="space-y-5">
      <PageHeader
        breadcrumb="Network"
        title="Traffic Analysis"
        description="Browse every flow record stored in SQLite. Each row is tagged with its origin so dataset replays, simulated demo rows and uploaded records are never confused."
        actions={
          <>
            <button
              type="button"
              className="btn btn-ghost"
              disabled={action !== null}
              onClick={() =>
                runAction('simulate', () => api.post('/api/traffic/simulate', { count: 50 }))
              }
            >
              <IconRefresh size={14} />
              {action === 'simulate' ? 'Generating…' : 'Add 50 simulated rows'}
            </button>
            <button
              type="button"
              className="btn btn-primary"
              disabled={action !== null || summary.data?.dataset_zip_present === false}
              title={
                summary.data?.dataset_zip_present === false
                  ? 'Download the CIC-IDS2017 archive first (see Settings).'
                  : undefined
              }
              onClick={() =>
                runAction('dataset', () => api.post('/api/traffic/load-dataset'))
              }
            >
              {action === 'dataset' ? 'Importing…' : 'Import CIC-IDS2017 records'}
            </button>
          </>
        }
      />

      <NoticeBanner tone="info" title="Where this traffic comes from">
        <span className="text-teal-300">CIC-IDS2017</span> rows are real labelled flows captured in
        July 2017 — their IPs, ports, protocol and timestamps are genuine.{' '}
        <span className="text-violet-300">Simulated</span> rows are synthetic and generated by this
        app; they are never scored by the model. Uploaded rows come from CSV files on the AI
        Detection page.
      </NoticeBanner>

      {actionError ? <ErrorState error={actionError} onRetry={() => setActionError(null)} /> : null}

      <Panel
        title="Filters"
        subtitle={`${formatNumber(list.data?.total ?? 0)} records match`}
        actions={
          <button
            type="button"
            className="btn btn-ghost"
            onClick={() => {
              setSearchDraft('')
              setParams(new URLSearchParams(), { replace: true })
            }}
          >
            Reset
          </button>
        }
      >
        <div className="flex flex-wrap items-end gap-3">
          <div>
            <div className="label-mono mb-1.5">Origin</div>
            <div className="flex flex-wrap gap-1.5">
              <Chip active={!origin} onClick={() => update({ origin: null })}>
                All
              </Chip>
              <Chip
                active={origin === 'dataset'}
                onClick={() => update({ origin: 'dataset' })}
                count={summary.data?.by_origin?.dataset}
              >
                CIC-IDS2017
              </Chip>
              <Chip
                active={origin === 'simulated'}
                onClick={() => update({ origin: 'simulated' })}
                count={summary.data?.by_origin?.simulated}
              >
                Simulated
              </Chip>
              <Chip
                active={origin === 'upload'}
                onClick={() => update({ origin: 'upload' })}
                count={summary.data?.by_origin?.upload}
              >
                Uploaded
              </Chip>
            </div>
          </div>

          <Field label="Attack category" className="w-48">
            <select
              className="field w-full"
              value={category}
              onChange={(e) => update({ category: e.target.value || null })}
            >
              <option value="">All categories</option>
              {CATEGORIES.map(([key, label]) => (
                <option key={key} value={key}>
                  {label} ({formatNumber(summary.data?.by_category?.[key] ?? 0)})
                </option>
              ))}
            </select>
          </Field>

          <Field label="Search" className="min-w-56 flex-1">
            <form
              onSubmit={(e) => {
                e.preventDefault()
                update({ q: searchDraft || null })
              }}
              className="relative"
            >
              <IconSearch
                size={14}
                className="pointer-events-none absolute left-2.5 top-1/2 -translate-y-1/2 text-mute-400"
              />
              <input
                className="field w-full pl-8"
                placeholder="IP address, port, protocol or label…"
                value={searchDraft}
                onChange={(e) => setSearchDraft(e.target.value)}
              />
            </form>
          </Field>
        </div>
      </Panel>

      {list.loading && !list.data ? (
        <PageLoader rows={8} />
      ) : list.error && !list.data ? (
        <ErrorState error={list.error} onRetry={list.refetch} />
      ) : items.length === 0 ? (
        <EmptyState
          icon="◌"
          title="No traffic records match these filters"
          description={
            <>
              Try clearing the filters, or populate the database with real CIC-IDS2017 records and
              simulated demo rows using the buttons in the page header.
            </>
          }
          action={
            <>
              <button
                type="button"
                className="btn btn-ghost"
                onClick={() => {
                  setSearchDraft('')
                  setParams(new URLSearchParams(), { replace: true })
                }}
              >
                Clear filters
              </button>
              <button
                type="button"
                className="btn btn-primary"
                onClick={() => runAction('simulate', () => api.post('/api/traffic/simulate', { count: 50 }))}
              >
                Generate demo traffic
              </button>
            </>
          }
        />
      ) : (
        <Panel bodyClassName="px-0 py-0">
          <div className="overflow-x-auto">
            <table className="w-full text-left text-[12.5px]">
              <thead className="sticky top-0 bg-ink-850">
                <tr className="label-mono border-b border-ink-600/70">
                  <th className="px-5 py-3 font-normal">Captured</th>
                  <th className="px-3 py-3 font-normal">Source</th>
                  <th className="px-3 py-3 font-normal">Destination</th>
                  <th className="px-3 py-3 font-normal">Proto</th>
                  <th className="px-3 py-3 text-right font-normal">Bytes</th>
                  <th className="px-3 py-3 text-right font-normal">Packets</th>
                  <th className="px-3 py-3 font-normal">Ground truth</th>
                  <th className="px-3 py-3 font-normal">Model prediction</th>
                  <th className="px-5 py-3 font-normal">Origin</th>
                </tr>
              </thead>
              <tbody>
                {items.map((r) => (
                  <tr
                    key={r.id}
                    className="table-row-hover cursor-pointer border-b border-ink-700/50"
                    onClick={() => openDetail(r.id)}
                  >
                    <td className="px-5 py-2.5">
                      <div className="text-slate-200" title={formatTimestamp(r.captured_at)}>
                        {relativeTime(r.captured_at)}
                      </div>
                      <div className="font-mono text-[10.5px] text-mute-400">
                        {formatTimestamp(r.captured_at)}
                      </div>
                    </td>
                    <td className="px-3 py-2.5 font-mono text-[11.5px] text-mute-200">
                      {r.source_ip ?? <span className="text-mute-400/60">—</span>}
                      {r.source_port ? (
                        <span className="text-mute-400">:{r.source_port}</span>
                      ) : null}
                    </td>
                    <td className="px-3 py-2.5 font-mono text-[11.5px] text-mute-200">
                      {r.destination_ip ?? <span className="text-mute-400/60">—</span>}
                      {r.destination_port ? (
                        <span className="text-cyan-300/80">:{r.destination_port}</span>
                      ) : null}
                    </td>
                    <td className="px-3 py-2.5 text-[11.5px] text-mute-300">
                      {r.protocol ?? '—'}
                    </td>
                    <td className="px-3 py-2.5 text-right tabular-nums text-mute-300">
                      {formatBytes(r.total_bytes)}
                    </td>
                    <td className="px-3 py-2.5 text-right tabular-nums text-mute-300">
                      {formatNumber(r.total_packets)}
                    </td>
                    <td className="px-3 py-2.5">
                      {r.origin === 'simulated' ? (
                        <Badge className="border-ink-600 bg-ink-800 text-mute-400">
                          n/a (simulated)
                        </Badge>
                      ) : (
                        <span
                          className={`text-[12px] ${
                            r.is_attack ? 'text-rose-300' : 'text-emerald-300'
                          }`}
                        >
                          {r.category_label}
                        </span>
                      )}
                    </td>
                    <td className="px-3 py-2.5">
                      {r.prediction ? (
                        <div className="flex items-center gap-2">
                          <span
                            className={
                              r.prediction.is_attack ? 'text-rose-300' : 'text-emerald-300'
                            }
                          >
                            {r.prediction.predicted_label}
                          </span>
                          <span className="font-mono text-[10.5px] text-mute-400">
                            {(r.prediction.confidence ?? 0).toFixed(2)}
                          </span>
                        </div>
                      ) : (
                        <span className="text-[11px] text-mute-400/70">
                          {r.origin === 'simulated' ? 'not scored' : 'pending'}
                        </span>
                      )}
                    </td>
                    <td className="px-5 py-2.5">
                      <OriginBadge
                        origin={r.origin}
                        title={r.origin_detail ?? undefined}
                      />
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <div className="px-5 pb-4">
            <Pagination
              page={list.data?.page ?? 1}
              pages={list.data?.pages ?? 1}
              total={list.data?.total ?? 0}
              onPage={(next) => update({ page: String(next) })}
            />
          </div>
        </Panel>
      )}

      {detail ? (
        <TrafficDetail record={detail} onClose={() => setDetail(null)} />
      ) : null}
    </div>
  )
}

function TrafficDetail({ record, onClose }: { record: TrafficRecord; onClose: () => void }) {
  const features = record.features ?? {}
  const topFeatures = Object.entries(features)
    .filter(([, v]) => typeof v === 'number')
    .sort((a, b) => Math.abs(b[1] as number) - Math.abs(a[1] as number))
    .slice(0, 12)

  return (
    <div className="fixed inset-0 z-50 flex items-start justify-center overflow-y-auto bg-black/70 p-4 backdrop-blur-sm">
      <div className="panel panel-glow mt-8 w-full max-w-3xl">
        <header className="flex items-start justify-between gap-4 border-b border-ink-600/70 px-5 py-4">
          <div>
            <div className="label-mono">Traffic record #{record.id}</div>
            <h3 className="mt-1 text-base font-semibold text-white">
              {record.source_ip ?? '—'}:{record.source_port ?? ''} →{' '}
              {record.destination_ip ?? '—'}:{record.destination_port ?? ''}
            </h3>
            <div className="mt-2 flex flex-wrap gap-1.5">
              <SeverityBadge severity={record.severity} />
              <OriginBadge origin={record.origin} title={record.origin_detail ?? undefined} />
              <Badge className="border-ink-600 bg-ink-800 text-mute-300">
                {record.protocol ?? 'unknown proto'}
              </Badge>
            </div>
          </div>
          <button type="button" className="btn btn-ghost" onClick={onClose}>
            Close
          </button>
        </header>

        <div className="space-y-4 px-5 py-4">
          <dl className="grid grid-cols-2 gap-3 sm:grid-cols-4">
            <Fact label="Captured" value={formatTimestamp(record.captured_at)} />
            <Fact label="Duration" value={formatDuration(record.flow_duration_ms)} />
            <Fact label="Total bytes" value={formatBytes(record.total_bytes)} />
            <Fact label="Packets" value={formatNumber(record.total_packets)} />
            <Fact label="Forward bytes" value={formatBytes(record.fwd_bytes)} />
            <Fact label="Backward bytes" value={formatBytes(record.bwd_bytes)} />
            <Fact label="Bytes / sec" value={formatNumber(record.bytes_per_sec, 1)} />
            <Fact label="Packets / sec" value={formatNumber(record.packets_per_sec, 2)} />
          </dl>

          <div className="rounded-xl border border-ink-600 bg-ink-850/60 px-4 py-3">
            <div className="label-mono">Ground truth label</div>
            <p className="mt-1 text-[13px] text-slate-200">
              {record.origin === 'simulated'
                ? 'Not applicable — this row was synthesised by the demo generator.'
                : `${record.label ?? 'unlabelled'} → category “${record.category_label}”`}
            </p>
            {record.origin_detail ? (
              <p className="mt-1 text-[11px] text-mute-400">{record.origin_detail}</p>
            ) : null}
          </div>

          {record.prediction ? (
            <div className="rounded-xl border border-cyan-400/25 bg-cyan-400/5 px-4 py-3">
              <div className="flex items-center justify-between gap-3">
                <div className="label-mono">Model prediction</div>
                <span className="font-mono text-[11px] text-mute-400">
                  {record.prediction.model_version}
                </span>
              </div>
              <p className="mt-1.5 text-[13px]">
                <span
                  className={
                    record.prediction.is_attack ? 'font-semibold text-rose-300' : 'font-semibold text-emerald-300'
                  }
                >
                  {record.prediction.predicted_label}
                </span>
                <span className="ml-2 text-mute-400">
                  confidence {((record.prediction.confidence ?? 0) * 100).toFixed(2)}%
                </span>
              </p>
              {record.prediction.probabilities ? (
                <ul className="mt-2 space-y-1 text-[11px]">
                  {Object.entries(record.prediction.probabilities)
                    .sort((a, b) => b[1] - a[1])
                    .slice(0, 5)
                    .map(([cls, p]) => (
                      <li key={cls} className="flex items-center gap-2">
                        <span className="w-24 truncate text-mute-400">{cls}</span>
                        <span className="h-1.5 flex-1 overflow-hidden rounded-full bg-ink-700">
                          <span
                            className="block h-full rounded-full bg-cyan-400/80"
                            style={{ width: `${p * 100}%` }}
                          />
                        </span>
                        <span className="w-12 text-right tabular-nums text-mute-300">
                          {(p * 100).toFixed(1)}%
                        </span>
                      </li>
                    ))}
                </ul>
              ) : null}
            </div>
          ) : (
            <div className="rounded-xl border border-ink-600 bg-ink-850/60 px-4 py-3">
              <p className="text-[12px] text-mute-400">
                {record.origin === 'simulated'
                  ? 'Simulated rows carry no CICFlowMeter feature vector, so the model cannot score them — by design.'
                  : 'This record has not been scored by the model yet.'}
              </p>
            </div>
          )}

          {topFeatures.length > 0 ? (
            <div>
              <div className="label-mono mb-2">
                Flow features ({Object.keys(features).length} stored)
              </div>
              <div className="grid grid-cols-2 gap-x-4 gap-y-1.5 sm:grid-cols-3">
                {topFeatures.map(([name, value]) => (
                  <div
                    key={name}
                    className="flex items-center justify-between gap-2 border-b border-ink-700/50 py-1 text-[11px]"
                  >
                    <span className="truncate text-mute-400" title={name}>
                      {name}
                    </span>
                    <span className="font-mono tabular-nums text-slate-300">
                      {Number(value).toFixed(2)}
                    </span>
                  </div>
                ))}
              </div>
            </div>
          ) : null}
        </div>
      </div>
    </div>
  )
}

function Fact({ label, value }: { label: string; value: string }) {
  return (
    <div className="rounded-lg border border-ink-600 bg-ink-850/60 px-3 py-2">
      <dt className="label-mono">{label}</dt>
      <dd className="mt-0.5 text-[12.5px] text-slate-200 tabular-nums">{value}</dd>
    </div>
  )
}
